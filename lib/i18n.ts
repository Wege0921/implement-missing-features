const translations: Record<string, Record<TranslationKey, string>> = {
  en: {} as Record<TranslationKey, string>,
  am: {} as Record<TranslationKey, string>,
}

export function registerTranslations(
  lang: 'en' | 'am',
  dict: Record<TranslationKey, string>
) {
  translations[lang] = { ...translations[lang], ...dict }
}

export function useTranslation() {
  const { language } = useAppStore()

  function t(key: TranslationKey, vars?: Record<string, string>): string {
    let text = translations[language]?.[key] ?? translations['en']?.[key] ?? key
    if (vars) {
      for (const [k, v] of Object.entries(vars)) {
        text = text.replace(new RegExp(`{${k}}`, 'g'), v)
      }
    }
    return text
  }

  return { t, language }
}

export function tServer(lang: 'en' | 'am', key: TranslationKey): string {
  return translations[lang]?.[key] ?? translations['en']?.[key] ?? key
}

// Auto-register translation dictionaries so any consumer of useTranslation
// (server or client bundles) has them available without a separate side-effect import.
registerTranslations('en', enDict)
registerTranslations('am', amDict)
